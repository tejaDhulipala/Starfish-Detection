"""Derive a full-frame split that moves some of a base split's val sequences into train.

Used for the train+val retrain and its dry run:
  - dry run: add half the val sequences to train, keep the other half as val (scores the new data,
    the stopping epoch and the cutoff shift on sequences nothing has trained on);
  - final: add every val sequence to train (val is then only a placeholder; train with val off).

Moved sequences follow the base split's rule for train: their frames with boxes become train
frames; their empty frames are marked 'added_empty' (not train, not val), so make_grid_split
can still draw empty tiles from them, as it does for every train sequence.

Writes data/yolo/splits/<name>/{split.csv,train.txt,val.txt,val_fast.txt} and data/yolo/<name>.yaml.
Then build tiles with: python -m src.data.make_grid_split --base <name>

Usage (from the repo root):
    python -m src.data.make_addval_split --half-seed 0 --name seq20val_pos_dryA      # dry run
    python -m src.data.make_addval_split --all --name seq20val_pos_trainval            # final
"""

import argparse
import csv

import numpy as np

from src.paths import YOLO_DATA, split_dir


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--base", default="seq20val_pos")
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--all", action="store_true", help="move every val sequence into train")
    g.add_argument("--half-seed", type=int, help="move the first half of np.random.default_rng(seed).permutation(val sequences)")
    ap.add_argument("--name", required=True)
    args = ap.parse_args()

    base = split_dir(args.base)
    rows = list(csv.DictReader(open(base / "split.csv")))
    val_seqs = sorted({r["sequence"] for r in rows if r["split"] == "val"})
    if args.all:
        moved = set(val_seqs)
    else:  # same halves as the held-out check in the ensemble scripts
        moved = {str(s) for s in np.random.default_rng(args.half_seed).permutation(val_seqs)[: len(val_seqs) // 2]}

    path = {p.rsplit("/", 2)[-2].split("_")[1] + "-" + p.rsplit("/", 1)[-1][:-4]: p
            for f in ("train.txt", "val.txt") for p in (base / f).read_text().splitlines()}
    for r in rows:
        if r["split"] == "val" and r["sequence"] in moved:
            r["split"] = "train" if int(r["n_boxes"]) > 0 else "added_empty"

    out = split_dir(args.name)
    out.mkdir(parents=True, exist_ok=True)
    with open(out / "split.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    train = [path[r["image_id"]] for r in rows if r["split"] == "train"]
    val = [path[r["image_id"]] for r in rows if r["split"] == "val"]
    if not val:  # Ultralytics needs a val list; train with val off when nothing is held out
        val = [path[r["image_id"]] for r in rows if r["sequence"] in moved][:: 50]
    (out / "train.txt").write_text("".join(f"{p}\n" for p in train))
    (out / "val.txt").write_text("".join(f"{p}\n" for p in val))
    (out / "val_fast.txt").write_text("".join(f"{p}\n" for p in val))
    (YOLO_DATA / f"{args.name}.yaml").write_text(
        f"# Generated by src/data/make_addval_split.py --base {args.base} "
        f"{'--all' if args.all else f'--half-seed {args.half_seed}'} --name {args.name}\n"
        f"# moved to train: sequences {', '.join(sorted(moved))}"
        f"{' (val is a placeholder: train with val off)' if args.all else ''}\n"
        f"path: {YOLO_DATA}\n"
        f"train: splits/{args.name}/train.txt\n"
        f"val: splits/{args.name}/val_fast.txt\n"
        "names:\n  0: cots\n")
    n_box = sum(int(r["n_boxes"]) for r in rows if r["split"] == "train")
    print(f"{args.name}: moved {sorted(moved)}; train {len(train)} frames ({n_box} boxes), val {len(val)} frames")


if __name__ == "__main__":
    main()
